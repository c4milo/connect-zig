//! Writes one `<file>.pb.zig` for one .proto file: its messages, its enums and its services
//! (design §8 step 6). The output is a pure function of the request, so `buf generate` writes
//! the same octets on every host, which CI compares with the committed code.
const std = @import("std");
const Allocator = std.mem.Allocator;
const pb = @import("descriptor_pb.zig");
const names = @import("names.zig");
const index_file = @import("index.zig");
const Index = index_file.Index;

pub const Error = index_file.Error;

const Out = struct {
    arena: Allocator,
    bytes: std.ArrayList(u8) = .empty,
    index: *const Index,
    file: []const u8,
    /// Whether the file is proto2, where a singular scalar has presence and a repeated scalar is
    /// unpacked unless it says otherwise.
    proto2: bool,

    fn print(out: *Out, comptime format: []const u8, args: anytype) Allocator.Error!void {
        try out.bytes.print(out.arena, format, args);
    }

    fn indent(out: *Out, depth: usize) Allocator.Error!void {
        for (0..depth) |_| try out.bytes.appendSlice(out.arena, "    ");
    }
};

pub fn file(arena: Allocator, index: *const Index, descriptor: pb.FileDescriptorProto) Error![]const u8 {
    const path = descriptor.name orelse "";
    const syntax = descriptor.syntax orelse "proto2";
    var out: Out = .{ .arena = arena, .index = index, .file = path, .proto2 = std.mem.eql(u8, syntax, "proto2") };
    try out.print("//! Code generated by protoc-gen-connect-zig. DO NOT EDIT.\n//! source: {s}\n", .{path});
    try out.print("const proto = @import(\"protobuf\");\n", .{});
    if (descriptor.service.view.bytes.len != 0 or descriptor.service.items.len != 0) try out.print("const connect = @import(\"connect\");\n", .{});
    try write_imports(&out, descriptor);
    var messages = descriptor.message_type.iterator();
    while (try messages.next()) |message| try write_message(&out, descriptor.package orelse "", message, 0);
    var enums = descriptor.enum_type.iterator();
    while (try enums.next()) |enumeration| try write_enum(&out, descriptor.package orelse "", enumeration, 0);
    var services = descriptor.service.iterator();
    while (try services.next()) |service| try write_service(&out, descriptor.package orelse "", service);
    return out.bytes.items;
}

fn write_imports(out: *Out, descriptor: pb.FileDescriptorProto) Error!void {
    var dependencies = descriptor.dependency.iterator();
    while (try dependencies.next()) |dependency| {
        // The well-known types live in the runtime, `proto.wkt`.
        if (std.mem.startsWith(u8, dependency, "google/protobuf/")) continue;
        const target = try names.output_path(out.arena, dependency);
        const relative = try names.relative_import(out.arena, try names.output_path(out.arena, out.file), target);
        try out.print("const {s} = @import(\"{s}\");\n", .{ try names.import_name(out.arena, dependency), relative });
    }
}

fn full_name(arena: Allocator, scope: []const u8, name: []const u8) Allocator.Error![]const u8 {
    if (scope.len == 0) return name;
    return std.fmt.allocPrint(arena, "{s}.{s}", .{ scope, name });
}

/// A field with the name the oneof's union holds it under, or none.
const Member = struct { field: pb.FieldDescriptorProto, oneof: ?[]const u8 };

fn write_message(out: *Out, scope: []const u8, message: pb.DescriptorProto, depth: usize) Error!void {
    const name = message.name orelse "";
    const full = try full_name(out.arena, scope, name);
    const fields = try collect_fields(out, message);
    try out.print("\n", .{});
    try out.indent(depth);
    try out.print("pub const {s} = struct {{\n", .{try names.identifier(out.arena, name)});
    try write_struct_fields(out, full, fields, depth + 1);
    try write_descriptor(out, full, message, fields, depth + 1);
    var nested = message.nested_type.iterator();
    while (try nested.next()) |child| try write_message(out, full, child, depth + 1);
    var enums = message.enum_type.iterator();
    while (try enums.next()) |enumeration| try write_enum(out, full, enumeration, depth + 1);
    try out.indent(depth);
    try out.print("}};\n", .{});
}

/// The message's fields, each with its real oneof's Zig name. A proto3 `optional` field sits in a
/// synthetic oneof, which the generator writes as a `?T` field instead.
fn collect_fields(out: *Out, message: pb.DescriptorProto) Error![]Member {
    var oneofs: std.ArrayList([]const u8) = .empty;
    var decls = message.oneof_decl.iterator();
    while (try decls.next()) |decl| try oneofs.append(out.arena, try names.field_identifier(out.arena, decl.name orelse ""));
    var members: std.ArrayList(Member) = .empty;
    var fields = message.field.iterator();
    while (try fields.next()) |field| {
        const synthetic = field.proto3_optional orelse false;
        const oneof: ?[]const u8 = if (field.oneof_index) |at| (if (synthetic) null else oneofs.items[@intCast(at)]) else null;
        try members.append(out.arena, .{ .field = field, .oneof = oneof });
    }
    return members.items;
}

fn write_struct_fields(out: *Out, full: []const u8, fields: []const Member, depth: usize) Error!void {
    for (fields, 0..) |member, at| {
        if (member.oneof) |oneof| {
            if (!first_of_oneof(fields, at)) continue;
            try write_oneof(out, full, fields, oneof, depth);
            continue;
        }
        const field = member.field;
        try out.indent(depth);
        try out.print("{s}: {s} = {s},\n", .{
            try names.field_identifier(out.arena, field.name orelse ""),
            try zig_type(out, full, field),
            try default_value(out, full, field),
        });
    }
}

fn first_of_oneof(fields: []const Member, at: usize) bool {
    for (fields[0..at]) |earlier| {
        if (earlier.oneof != null and std.mem.eql(u8, earlier.oneof.?, fields[at].oneof.?)) return false;
    }
    return true;
}

fn write_oneof(out: *Out, full: []const u8, fields: []const Member, oneof: []const u8, depth: usize) Error!void {
    try out.indent(depth);
    try out.print("{s}: ?union(enum) {{\n", .{oneof});
    for (fields) |member| {
        const name = member.oneof orelse continue;
        if (!std.mem.eql(u8, name, oneof)) continue;
        try out.indent(depth + 1);
        try out.print("{s}: {s},\n", .{ try names.field_identifier(out.arena, member.field.name orelse ""), try value_type(out, full, member.field) });
    }
    try out.indent(depth);
    try out.print("}} = null,\n", .{});
}

/// The type of one value of a field, without repetition or presence.
fn value_type(out: *Out, container: []const u8, field: pb.FieldDescriptorProto) Error![]const u8 {
    const kind = field.type orelse return error.UnknownType;
    return switch (kind) {
        .int32, .sint32, .sfixed32 => "i32",
        .int64, .sint64, .sfixed64 => "i64",
        .uint32, .fixed32 => "u32",
        .uint64, .fixed64 => "u64",
        .float => "f32",
        .double => "f64",
        .bool => "bool",
        .string, .bytes => "[]const u8",
        .@"enum" => out.index.reference(out.arena, out.file, index_file.strip_dot(field.type_name orelse "")),
        .message => message_type(out, container, field),
        else => error.UnknownType,
    };
}

fn message_type(out: *Out, container: []const u8, field: pb.FieldDescriptorProto) Error![]const u8 {
    const target = index_file.strip_dot(field.type_name orelse "");
    const reference = try out.index.reference(out.arena, out.file, target);
    if (field.label == .repeated) return reference;
    if (try out.index.is_recursive(out.arena, container, target)) return std.fmt.allocPrint(out.arena, "proto.Lazy({s})", .{reference});
    return reference;
}

fn zig_type(out: *Out, container: []const u8, field: pb.FieldDescriptorProto) Error![]const u8 {
    const value = try value_type(out, container, field);
    if (field.label == .repeated) return std.fmt.allocPrint(out.arena, "proto.Repeated({s}, .{s})", .{ value, kind_name(field.type.?) });
    if (field.type == .message) return if (std.mem.startsWith(u8, value, "proto.Lazy(")) value else std.fmt.allocPrint(out.arena, "?{s}", .{value});
    if (has_presence(out, field)) return std.fmt.allocPrint(out.arena, "?{s}", .{value});
    return value;
}

/// Whether a scalar field has explicit presence: proto3 `optional`, or a proto2 singular field
/// outside a oneof (language guide, "Field Presence").
fn has_presence(out: *const Out, field: pb.FieldDescriptorProto) bool {
    if (field.proto3_optional orelse false) return true;
    return out.proto2 and field.label != .repeated and field.oneof_index == null;
}

/// Whether a repeated packable field is written unpacked: proto3 packs unless the field says
/// `packed = false`, and proto2 packs only when it says `packed = true` ("Packed Repeated Fields").
fn unpacked(out: *const Out, field: pb.FieldDescriptorProto) bool {
    if (field.label != .repeated) return false;
    switch (field.type orelse return false) {
        .string, .bytes, .message, .group => return false,
        else => {},
    }
    const stated: ?bool = if (field.options) |options| options.@"packed" else null;
    if (stated) |packed_flag| return !packed_flag;
    return out.proto2;
}

fn default_value(out: *Out, container: []const u8, field: pb.FieldDescriptorProto) Error![]const u8 {
    const type_text = try zig_type(out, container, field);
    if (field.label == .repeated or std.mem.startsWith(u8, type_text, "proto.Lazy(")) return ".{}";
    if (type_text[0] == '?') return "null";
    return switch (field.type.?) {
        .string, .bytes => "\"\"",
        .bool => "false",
        .@"enum" => "@enumFromInt(0)",
        else => "0",
    };
}

pub fn kind_name(kind: pb.Type) []const u8 {
    return switch (kind) {
        .@"enum" => "@\"enum\"",
        .bool => "bool",
        else => @tagName(kind),
    };
}

fn write_descriptor(out: *Out, full: []const u8, message: pb.DescriptorProto, fields: []const Member, depth: usize) Error!void {
    const sorted = try out.arena.dupe(Member, fields);
    std.mem.sort(Member, sorted, {}, by_number);
    const map_entry = if (message.options) |options| options.map_entry orelse false else false;
    try out.print("\n", .{});
    try out.indent(depth);
    try out.print("pub const protobuf: proto.Descriptor = .{{\n", .{});
    try out.indent(depth + 1);
    try out.print(".full_name = {s},\n", .{try names.string_literal(out.arena, full)});
    if (map_entry) {
        try out.indent(depth + 1);
        try out.print(".map_entry = true,\n", .{});
    }
    try out.indent(depth + 1);
    if (sorted.len == 0) return finish_descriptor(out, depth, ".fields = &.{},\n");
    try out.print(".fields = &.{{\n", .{});
    for (sorted) |member| try write_field_entry(out, member, depth + 2);
    try out.indent(depth + 1);
    try finish_descriptor(out, depth, "},\n");
}

fn finish_descriptor(out: *Out, depth: usize, tail: []const u8) Error!void {
    try out.print("{s}", .{tail});
    try out.indent(depth);
    try out.print("}};\n", .{});
}

fn by_number(_: void, a: Member, b: Member) bool {
    return (a.field.number orelse 0) < (b.field.number orelse 0);
}

fn write_field_entry(out: *Out, member: Member, depth: usize) Error!void {
    const field = member.field;
    const name = field.name orelse "";
    try out.indent(depth);
    try out.print(".{{ .name = {s}, .number = {d}, .kind = .{s}, .json_name = {s}, .proto_name = {s}", .{
        try names.string_literal(out.arena, name),
        field.number orelse 0,
        kind_name(field.type orelse .int32),
        try names.string_literal(out.arena, field.json_name orelse name),
        try names.string_literal(out.arena, name),
    });
    if (member.oneof) |oneof| try out.print(", .oneof = {s}", .{try names.string_literal(out.arena, unescaped(oneof))});
    if (unpacked(out, field)) try out.print(", .@\"packed\" = false", .{});
    try out.print(" }},\n", .{});
}

/// A Zig name without its `@"..."` quoting, as `@field` takes it.
fn unescaped(name: []const u8) []const u8 {
    if (std.mem.startsWith(u8, name, "@\"")) return name[2 .. name.len - 1];
    return name;
}

fn write_enum(out: *Out, scope: []const u8, enumeration: pb.EnumDescriptorProto, depth: usize) Error!void {
    const name = enumeration.name orelse "";
    const full = try full_name(out.arena, scope, name);
    try out.print("\n", .{});
    try out.indent(depth);
    try out.print("pub const {s} = enum(i32) {{\n", .{try names.identifier(out.arena, name)});
    var seen: std.AutoHashMapUnmanaged(i32, void) = .empty;
    var values = enumeration.value.iterator();
    while (try values.next()) |value| {
        const number = value.number orelse 0;
        // An alias repeats a number, which a Zig enum cannot; the table below keeps its name.
        if ((try seen.getOrPut(out.arena, number)).found_existing) continue;
        try out.indent(depth + 1);
        try out.print("{s} = {d},\n", .{ try names.field_identifier(out.arena, try names.snake_case(out.arena, value.name orelse "")), number });
    }
    try out.indent(depth + 1);
    try out.print("_,\n\n", .{});
    try out.indent(depth + 1);
    try out.print("pub const protobuf: proto.EnumDescriptor = .{{ .full_name = {s}, .values = &.{{\n", .{try names.string_literal(out.arena, full)});
    var named = enumeration.value.iterator();
    while (try named.next()) |value| {
        try out.indent(depth + 2);
        try out.print(".{{ .name = {s}, .number = {d} }},\n", .{ try names.string_literal(out.arena, value.name orelse ""), value.number orelse 0 });
    }
    try out.indent(depth + 1);
    try out.print("}} }};\n", .{});
    try out.indent(depth);
    try out.print("}};\n", .{});
}

fn write_service(out: *Out, package: []const u8, service: pb.ServiceDescriptorProto) Error!void {
    const name = service.name orelse "";
    try out.print("\npub const {s} = struct {{\n", .{try names.identifier(out.arena, name)});
    try out.print("    pub const service_name = {s};\n", .{try names.string_literal(out.arena, try full_name(out.arena, package, name))});
    var methods = service.method.iterator();
    while (try methods.next()) |method| try write_method(out, method);
    try out.print("}};\n", .{});
}

fn write_method(out: *Out, method: pb.MethodDescriptorProto) Error!void {
    const client_stream = method.client_streaming orelse false;
    const server_stream = method.server_streaming orelse false;
    const stream_type = if (client_stream and server_stream) "bidi_stream" else if (client_stream) "client_stream" else if (server_stream) "server_stream" else "unary";
    const level = if (method.options) |options| options.idempotency_level orelse .idempotency_unknown else .idempotency_unknown;
    const idempotency = switch (level) {
        .no_side_effects => "no_side_effects",
        .idempotent => "idempotent",
        else => "unknown",
    };
    const method_name = method.name orelse "";
    try out.print("\n    pub const {s}: connect.Method = .{{\n", .{try names.identifier(out.arena, try names.snake_case(out.arena, method_name))});
    try out.print("        .service = service_name,\n        .name = {s},\n", .{try names.string_literal(out.arena, method_name)});
    try out.print("        .Request = {s},\n", .{try out.index.reference(out.arena, out.file, index_file.strip_dot(method.input_type orelse ""))});
    try out.print("        .Response = {s},\n", .{try out.index.reference(out.arena, out.file, index_file.strip_dot(method.output_type orelse ""))});
    try out.print("        .stream_type = .{s},\n        .idempotency = .{s},\n    }};\n", .{ stream_type, idempotency });
}
