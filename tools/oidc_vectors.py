#!/usr/bin/env python3
"""Writes src/oidc/rsa_vectors.zig: RS256 tokens that OpenSSL signed, and their public keys.

Run: python3 tools/oidc_vectors.py. It needs openssl on the path. Each run makes new keys, and
keeps no private key, so the tokens and the keys change together.
"""
import base64
import json
import pathlib
import subprocess
import tempfile

ISSUER = "https://issuer.example"
AUDIENCE = "service"
SUBJECT = "user-1"
EXPIRES = 2000000000
SIZES = (1024, 2048, 4096)
WIDTH = 92


def base64url(octets):
    return base64.urlsafe_b64encode(octets).rstrip(b"=").decode()


def openssl(*arguments, data=None):
    return subprocess.run(("openssl",) + arguments, input=data, capture_output=True, check=True).stdout


def vector(bits, folder):
    """A key of `bits` bits, and a token it signed: (modulus, token), both text."""
    key = str(pathlib.Path(folder) / f"rsa-{bits}.pem")
    openssl("genpkey", "-algorithm", "RSA", "-pkeyopt", f"rsa_keygen_bits:{bits}", "-out", key)
    modulus = openssl("rsa", "-in", key, "-noout", "-modulus").decode().strip().split("=")[1]
    header = {"alg": "RS256", "typ": "JWT", "kid": f"rsa-{bits}"}
    claims = {"iss": ISSUER, "sub": SUBJECT, "aud": AUDIENCE, "exp": EXPIRES}
    parts = [base64url(json.dumps(part, separators=(",", ":")).encode()) for part in (header, claims)]
    signed = ".".join(parts).encode()
    signature = openssl("dgst", "-sha256", "-sign", key, "-binary", data=signed)
    return base64url(bytes.fromhex(modulus)), signed.decode() + "." + base64url(signature)


def constant(name, text):
    lines = [text[at : at + WIDTH] for at in range(0, len(text), WIDTH)]
    if len(lines) == 1:
        return f'pub const {name} = "{text}";\n'
    joined = " ++\n".join(f'    "{line}"' for line in lines)
    return f"pub const {name} =\n{joined};\n"


def main():
    out = "//! Generated by tools/oidc_vectors.py; regenerate, never edit.\n"
    out += "//! RS256 tokens that OpenSSL signed, and the modulus of each key. The exponent is 65537.\n"
    out += "//! The 1024-bit key is under RFC 7518 §3.3's 2048 bits, so a verifier does not keep it.\n\n"
    out += f'pub const issuer = "{ISSUER}";\n'
    out += f'pub const audience = "{AUDIENCE}";\n'
    out += f'pub const subject = "{SUBJECT}";\n'
    out += f"pub const expires_unix_seconds = {EXPIRES};\n"
    out += 'pub const exponent = "AQAB";\n'
    with tempfile.TemporaryDirectory() as folder:
        for bits in SIZES:
            modulus, token = vector(bits, folder)
            out += f"\n/// The key's \"kid\" is \"rsa-{bits}\".\n"
            out += constant(f"rsa_{bits}_modulus", modulus)
            out += constant(f"rsa_{bits}_token", token)
    root = pathlib.Path(__file__).resolve().parent.parent
    (root / "src" / "oidc" / "rsa_vectors.zig").write_text(out)


if __name__ == "__main__":
    main()
